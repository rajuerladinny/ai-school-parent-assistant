-- PostgreSQL baseline for the multi-school School Parent Assistant.
-- This is a fresh-install schema, not yet a data migration from SQLite.
BEGIN;
CREATE TABLE IF NOT EXISTS schools (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slug TEXT NOT NULL UNIQUE, name TEXT NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS parent_accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 school_id BIGINT NOT NULL REFERENCES schools(id),
 username TEXT NOT NULL, display_name TEXT NOT NULL,
 salt TEXT NOT NULL, password_hash TEXT NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 UNIQUE(school_id,username)
);
CREATE TABLE IF NOT EXISTS parent_sessions (
 token_hash TEXT PRIMARY KEY,
 parent_id BIGINT NOT NULL REFERENCES parent_accounts(id) ON DELETE CASCADE,
 expires_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS knowledge (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 school_id BIGINT NOT NULL REFERENCES schools(id),
 topic TEXT NOT NULL, answer TEXT NOT NULL, source TEXT NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS documents (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 school_id BIGINT NOT NULL REFERENCES schools(id),
 filename TEXT NOT NULL, title TEXT NOT NULL, content TEXT NOT NULL,
 uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS policy_versions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 school_id BIGINT NOT NULL REFERENCES schools(id),
 policy_key TEXT NOT NULL, version INTEGER NOT NULL CHECK(version>0),
 title TEXT NOT NULL, filename TEXT NOT NULL, content TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','approved','rejected')),
 effective_date DATE NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 reviewed_at TIMESTAMPTZ,
 UNIQUE(school_id,policy_key,version)
);
CREATE TABLE IF NOT EXISTS escalations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 school_id BIGINT NOT NULL REFERENCES schools(id),
 parent_id BIGINT REFERENCES parent_accounts(id),
 question TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open','assigned','resolved')),
 assigned_to TEXT, resolution TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 updated_at TIMESTAMPTZ, resolved_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS escalation_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 escalation_id BIGINT NOT NULL REFERENCES escalations(id) ON DELETE CASCADE,
 action TEXT NOT NULL, detail TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
-- School-specific staff identities and expiring bearer sessions.
CREATE TABLE IF NOT EXISTS staff_accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 school_id BIGINT NOT NULL REFERENCES schools(id),
 username TEXT NOT NULL UNIQUE,
 display_name TEXT NOT NULL, salt TEXT NOT NULL, password_hash TEXT NOT NULL,
 role TEXT NOT NULL CHECK(role IN ('school_admin','staff')),
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS staff_sessions (
 token_hash TEXT PRIMARY KEY,
 staff_id BIGINT NOT NULL REFERENCES staff_accounts(id) ON DELETE CASCADE,
 expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_staff_accounts_school ON staff_accounts(school_id);
CREATE TABLE IF NOT EXISTS parent_notification_reads (
 parent_id BIGINT NOT NULL REFERENCES parent_accounts(id) ON DELETE CASCADE,
 policy_id BIGINT NOT NULL REFERENCES policy_versions(id) ON DELETE CASCADE,
 read_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 PRIMARY KEY(parent_id,policy_id)
);
-- Enforce tenant consistency even for writes outside the HTTP API.
CREATE OR REPLACE FUNCTION enforce_parent_notification_school()
RETURNS TRIGGER LANGUAGE plpgsql AS $
BEGIN
 IF NOT EXISTS (
   SELECT 1 FROM parent_accounts a
   JOIN policy_versions p ON p.id=NEW.policy_id
   WHERE a.id=NEW.parent_id AND a.school_id=p.school_id
 ) THEN
   RAISE EXCEPTION 'Parent and policy must belong to the same school'
     USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END;
$;
DROP TRIGGER IF EXISTS trg_parent_notification_school ON parent_notification_reads;
CREATE TRIGGER trg_parent_notification_school
BEFORE INSERT OR UPDATE OF parent_id,policy_id ON parent_notification_reads
FOR EACH ROW EXECUTE FUNCTION enforce_parent_notification_school();
CREATE TABLE IF NOT EXISTS knowledge_conflicts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 policy_id BIGINT NOT NULL REFERENCES policy_versions(id) ON DELETE CASCADE,
 legacy_type TEXT NOT NULL CHECK(legacy_type IN ('faq','document')),
 legacy_id BIGINT NOT NULL,
 status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open','resolved')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), resolved_at TIMESTAMPTZ,
 UNIQUE(policy_id,legacy_type,legacy_id)
);
CREATE INDEX IF NOT EXISTS idx_knowledge_school ON knowledge(school_id);
CREATE INDEX IF NOT EXISTS idx_documents_school ON documents(school_id);
CREATE INDEX IF NOT EXISTS idx_policy_versions_school ON policy_versions(school_id,policy_key,status,effective_date);
CREATE INDEX IF NOT EXISTS idx_escalations_school ON escalations(school_id,status);
COMMIT;
